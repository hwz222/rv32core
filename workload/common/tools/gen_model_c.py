#!/usr/bin/env python3
"""Turn a quantized model (model.json + weights.bin) into C source.

Build-time tool: it uses only the Python standard library, so building a
workload needs no numpy and no torch.

    gen_model_c.py model  --model-dir DIR --out PREFIX
        writes PREFIX.h and PREFIX.c: the weights as const arrays, the layer
        table for nn_int8.c, and a static activation arena.

    gen_model_c.py images --images FILE --start S --count N --out PREFIX
        writes PREFIX.h and PREFIX.c: N quantized input images
        (int8, 3x32x32 each) read from FILE, starting at image S.

The activation arena is planned here: each tensor gets a byte offset, and
a tensor's space is reused once no later layer reads it.
"""

import argparse
import json
import os
import sys

OPS = {"conv": "NN_CONV", "add": "NN_ADD", "gap": "NN_GAP", "fc": "NN_FC"}


def c_array(ctype, name, values, per_line=24):
    rows = []
    for i in range(0, len(values), per_line):
        rows.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return "static const %s %s[%d] = {\n%s\n};\n" % (ctype, name, len(values), "\n".join(rows))


def numel(shape):
    n = 1
    for d in shape:
        n *= d
    return n


def plan_arena(layers, input_bytes):
    """Give every tensor a byte offset. Returns ({tensor: offset}, arena size)."""
    size = {"input": input_bytes}
    last_use = {}
    for i, l in enumerate(layers):
        for t in (l["inputs"] if l["op"] == "add" else [l["input"]]):
            last_use[t] = i
        if l["op"] == "conv":
            size[l["output"]] = numel(l["out_shape"])
        elif l["op"] == "add":
            size[l["output"]] = numel(l["shape"])
        elif l["op"] == "gap":
            size[l["output"]] = l["in_shape"][0]

    live = []          # (offset, end, tensor)
    offset = {}
    top = 0

    def alloc(t):
        nonlocal top
        need = (size[t] + 3) & ~3              # keep 4-byte alignment
        pos = 0
        for start, end, _ in sorted(live):     # first fit
            if pos + need <= start:
                break
            pos = max(pos, end)
        live.append((pos, pos + need, t))
        offset[t] = pos
        top = max(top, pos + need)

    # The input image is read in place (NN_INPUT); it takes no arena space.
    for i, l in enumerate(layers):
        if l["op"] != "fc":
            alloc(l["output"])                 # inputs are still live here
        live[:] = [e for e in live if last_use.get(e[2], -1) > i]
    return offset, top


def gen_model(model_dir, prefix):
    model = json.load(open(os.path.join(model_dir, "model.json")))
    with open(os.path.join(model_dir, model["weights_file"]), "rb") as f:
        raw = f.read()
    assert len(raw) == model["weights_bytes"], "weights.bin has the wrong size"
    weights = [b - 256 if b > 127 else b for b in raw]      # bytes -> int8

    layers = model["layers"]
    c, h, w = model["input_shape"]
    offsets, arena = plan_arena(layers, c * h * w)
    where = lambda t: "NN_INPUT" if t == "input" else str(offsets[t])

    out = ['/* Generated by workload/common/tools/gen_model_c.py from %s.' % model_dir,
           ' * Do not edit, do not commit (build output). */',
           '#include "%s.h"' % os.path.basename(prefix), '']
    out.append(c_array("int8_t", "nn_weights", weights))
    table = []
    for i, l in enumerate(layers):
        op = l["op"]
        arrays = {}
        for key in ("bias", "m0", "shift"):
            if key in l:
                name = "L%d_%s" % (i, key)
                out.append(c_array("int32_t", name, l[key]))
                arrays[key] = name
        wptr = "nn_weights + %d" % l["weight_offset"] if "weight_offset" in l else "0"
        if op == "conv":
            (ci, hi, wi), (co, ho, wo) = l["in_shape"], l["out_shape"]
            geo = (l["kernel"], l["stride"], l["padding"], l["groups"])
            ins = (where(l["input"]), "0")
        elif op == "add":
            ci, hi, wi = co, ho, wo = l["shape"]
            geo = (0, 0, 0, 1)
            ins = (where(l["inputs"][0]), where(l["inputs"][1]))
        elif op == "gap":
            ci, hi, wi = l["in_shape"]
            co, ho, wo = ci, 1, 1
            geo = (0, 0, 0, 1)
            ins = (where(l["input"]), "0")
        else:  # fc
            ci, hi, wi = l["in_features"], 1, 1
            co, ho, wo = l["out_features"], 1, 1
            geo = (0, 0, 0, 1)
            ins = (where(l["input"]), "0")
        dst = "0" if op == "fc" else str(offsets[l["output"]])
        table.append("    /* %2d %-18s */ {%s, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %s, %s, %s, %s, %s, %s, %s},"
                     % (i, l["name"], OPS[op], 1 if l.get("relu") else 0, ci, hi, wi, co, ho, wo,
                        geo[0], geo[1], geo[2], geo[3], ins[0], ins[1], dst, wptr,
                        arrays.get("bias", "0"), arrays.get("m0", "0"), arrays.get("shift", "0")))
    out.append("static const nn_layer nn_layers[%d] = {\n%s\n};\n" % (len(layers), "\n".join(table)))
    out.append("const nn_model NN_MODEL = {nn_layers, %d, %d};\n" % (len(layers), model["num_classes"]))
    out.append("int8_t nn_arena[NN_ARENA_BYTES];")
    with open(prefix + ".c", "w") as f:
        f.write("\n".join(out) + "\n")

    hdr = ['/* Generated by workload/common/tools/gen_model_c.py. Do not edit. */',
           '#ifndef NN_MODEL_DATA_H', '#define NN_MODEL_DATA_H', '',
           '#include "nn_int8.h"', '',
           '/* %s: %d layers, %d weight bytes, arena %d bytes */'
           % (model["model"], len(layers), len(weights), arena),
           '#define NN_ARENA_BYTES %d' % arena,
           '#define NN_INPUT_BYTES %d' % (c * h * w),
           '#define NN_NUM_CLASSES %d' % model["num_classes"], '',
           'extern const nn_model NN_MODEL;',
           'extern int8_t nn_arena[NN_ARENA_BYTES];', '', '#endif']
    with open(prefix + ".h", "w") as f:
        f.write("\n".join(hdr) + "\n")
    print("generated %s.{c,h}: %d layers, %d weight bytes, arena %d bytes"
          % (prefix, len(layers), len(weights), arena))


def gen_images(path, start, count, prefix, image_bytes=3 * 32 * 32):
    with open(path, "rb") as f:
        f.seek(start * image_bytes)
        raw = f.read(count * image_bytes)
    assert len(raw) == count * image_bytes, "not enough images in " + path
    vals = [b - 256 if b > 127 else b for b in raw]
    rows = []
    for i in range(count):
        v = vals[i * image_bytes:(i + 1) * image_bytes]
        rows.append("    {" + ",".join(str(x) for x in v) + "},")
    body = ['/* Generated by workload/common/tools/gen_model_c.py: images %d..%d of %s.'
            % (start, start + count - 1, path), ' * Do not edit, do not commit. */',
            '#include "%s.h"' % os.path.basename(prefix), '',
            'const int8_t eval_images[EVAL_COUNT][%d] = {' % image_bytes] + rows + ['};']
    with open(prefix + ".c", "w") as f:
        f.write("\n".join(body) + "\n")
    hdr = ['/* Generated by workload/common/tools/gen_model_c.py. Do not edit. */',
           '#ifndef EVAL_IMAGES_H', '#define EVAL_IMAGES_H', '', '#include <stdint.h>', '',
           '#define EVAL_START %d' % start, '#define EVAL_COUNT %d' % count, '',
           'extern const int8_t eval_images[EVAL_COUNT][%d];' % image_bytes, '', '#endif']
    with open(prefix + ".h", "w") as f:
        f.write("\n".join(hdr) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("model")
    m.add_argument("--model-dir", required=True)
    m.add_argument("--out", required=True, help="output prefix (writes .c and .h)")
    im = sub.add_parser("images")
    im.add_argument("--images", required=True)
    im.add_argument("--start", type=int, required=True)
    im.add_argument("--count", type=int, required=True)
    im.add_argument("--out", required=True)
    a = ap.parse_args()
    if a.cmd == "model":
        gen_model(a.model_dir, a.out)
    else:
        gen_images(a.images, a.start, a.count, a.out)


if __name__ == "__main__":
    sys.exit(main())
