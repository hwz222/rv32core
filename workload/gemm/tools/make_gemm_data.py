#!/usr/bin/env python3
"""Write gemm_data.h: the two GEMM input matrices for one shape and seed.

    python3 tools/make_gemm_data.py M N K SEED gemm_data.h

The bare-metal program has no file system, so the inputs are compiled in as
C arrays. Both builds (host and RV32IMA) include the same generated header,
so they multiply exactly the same numbers.

Values are integers in [-7, 7]. Every product then fits in 6 bits, and a sum
of K of them stays far inside int32 for any K the 2 MB data memory can hold
(K <= 200000 gives |C| <= 9.8e6), so the result never depends on overflow
behaviour and the host and RV32IMA results must agree bit for bit.

Standard library only, and no `random`: its sequence is not promised to stay
the same across Python versions. xorshift32 is the generator instead.
"""
import sys


def xorshift32(seed):
    # The state must never be 0, so mix the seed in and force a set bit.
    x = (seed * 0x9E3779B9 + 0x7F4A7C15) & 0xFFFFFFFF or 1
    while True:
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        yield x


def matrix(name, rows, cols, rng):
    vals = [next(rng) % 15 - 7 for _ in range(rows * cols)]
    lines = [f"/* {name}: {rows} x {cols}, row-major */",
             f"const int32_t {name}[{rows * cols}] = {{"]
    for r in range(rows):
        row = vals[r * cols:(r + 1) * cols]
        for c in range(0, cols, 20):
            lines.append("    " + ",".join(f"{v:2d}" for v in row[c:c + 20]) + ",")
    lines.append("};")
    return lines


def main(argv):
    if len(argv) != 6:
        sys.exit("usage: make_gemm_data.py M N K SEED OUT")
    try:
        m, n, k, seed = (int(a) for a in argv[1:5])
    except ValueError:
        sys.exit("make_gemm_data.py: M, N, K and SEED must be integers")
    if min(m, n, k) < 1 or seed < 0:
        sys.exit(f"make_gemm_data.py: need M, N, K >= 1 and SEED >= 0 "
                 f"(got {m} {n} {k} {seed})")

    # A and B use separate streams so that changing K does not shift B.
    out = ["/* Generated by tools/make_gemm_data.py. Build output, not source. */",
           f"/* M={m} N={n} K={k} seed={seed} */",
           "#ifndef GEMM_DATA_H",
           "#define GEMM_DATA_H",
           "",
           "#include <stdint.h>",
           "",
           f"#define GEMM_M {m}",
           f"#define GEMM_N {n}",
           f"#define GEMM_K {k}",
           ""]
    out += matrix("gemm_a", m, k, xorshift32(2 * seed))
    out.append("")
    out += matrix("gemm_b", k, n, xorshift32(2 * seed + 1))
    out += ["", "#endif", ""]

    text = "\n".join(out)
    with open(argv[5], "w") as fh:
        fh.write(text)


if __name__ == "__main__":
    main(sys.argv)
